"""Regenerate tests/temporal_binds_reference.py: what python-oracledb sends for
every cell of the temporal bind grid (#1338).

python-oracledb thin runs each cell of ``tests/temporal_bind_grid.py`` against
an in-process passthrough Mirror in front of a real Oracle, and the Mirror keeps
the raw bytes of every bind it receives. A real server behind it answers the
dictionary lookups an object bind needs; the bytes recorded are the client's,
before the Mirror relays anything.

The scratch objects the cells use (one object type per temporal declaration and
a table) are created first and dropped afterwards.

Connection comes from the project's standard integration env vars:
    SEERDB_TEST_HOST (default 192.168.0.150), SEERDB_TEST_PORT (1523),
    SEERDB_TEST_SERVICE (FREEPDB1), SEERDB_TEST_USER, SEERDB_TEST_PASSWORD

Writes the module (or prints it with ``--stdout``).
"""

from __future__ import annotations

import os
import pprint
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [ROOT, os.path.join(ROOT, 'tests'), os.path.join(ROOT, 'examples')]

import oracledb  # noqa: E402
from oracle_passthrough_backend import OraclePassthroughBackend  # noqa: E402
from temporal_bind_grid import (  # noqa: E402
    OBJECT_TYPE_PREFIX,
    SQL_TYPE,
    capture,
    cells,
    mirror,
    object_type_name,
    recording,
)

import seerdb  # noqa: E402
from seerdb.server.framing import PacketStream  # noqa: E402
from seerdb.server.session import serve_session  # noqa: E402

HEADER = '''\
# SPDX-FileCopyrightText: 2019 Peter Lemenkov <lemenkov@gmail.com>
# SPDX-License-Identifier: MIT

"""What python-oracledb {version} sends for each cell of the temporal bind
grid (#1338). Generated by tools/temporal_bind_reference.py; do not edit.

REFERENCE maps a cell key to the bind's OAC ``[type, max size]`` and each row's
value as hex, length prefix included. OBJECT_TYPES holds what the object cells'
types looked like on the server they were captured from, so the offline test
can build the same types without one."""

'''


def setup(conn: seerdb.Connection) -> None:
    cursor = conn.cursor()
    teardown(conn)
    columns = ', '.join(f'{Short} {Sql}' for Sql, Short in SQL_TYPE.values())
    cursor.execute(f'create table {OBJECT_TYPE_PREFIX}T ({columns})')
    for declared, (sql_type, _short) in SQL_TYPE.items():
        cursor.execute(
            f'create type {object_type_name(declared)} as object (A {sql_type})'
        )


def teardown(conn: seerdb.Connection) -> None:
    cursor = conn.cursor()
    names = [object_type_name(D) for D in SQL_TYPE]
    for statement in [f'drop table {OBJECT_TYPE_PREFIX}T purge'] + [
        f'drop type {N} force' for N in names
    ]:
        try:
            cursor.execute(statement)
        except seerdb.DatabaseError:
            pass


def object_types(conn: seerdb.Connection) -> dict:
    out = {}
    for declared in SQL_TYPE:
        typ = conn.gettype(object_type_name(declared))
        out[typ.name] = {
            'schema': typ.schema,
            'oid': typ.oid.hex(),
            'version': typ.version,
            'attrs': typ.attrs,
        }
    return out


def main() -> int:
    host = os.environ.get('SEERDB_TEST_HOST', '192.168.0.150')
    port = int(os.environ.get('SEERDB_TEST_PORT', '1523'))
    service = os.environ.get('SEERDB_TEST_SERVICE', 'FREEPDB1')
    user = os.environ.get('SEERDB_TEST_USER', 'pyo')
    password = os.environ.get('SEERDB_TEST_PASSWORD', 'pyo123')

    direct = seerdb.connect(
        host=host, port=port, service_name=service, user=user, password=password
    )
    try:
        setup(direct)
        types = object_types(direct)
        field_version = direct.field_version

        def serve(sock) -> None:
            serve_session(
                PacketStream(sock),
                OraclePassthroughBackend(
                    host=host,
                    port=port,
                    service=service,
                    credentials={user.upper(): password},
                    field_version=field_version,
                ),
            )

        reference = {}
        with recording() as log, mirror(serve) as mirror_port:
            conn = oracledb.connect(
                user=user, password=password, dsn=f'127.0.0.1:{mirror_port}/{service}'
            )
            try:
                for cell in cells():
                    if not cell.seerdb_only:
                        reference[cell.key] = capture(conn, oracledb, log, cell)
            finally:
                conn.close()
    finally:
        teardown(direct)
        direct.close()

    text = (
        HEADER.format(version=oracledb.__version__)
        + f'OBJECT_TYPES = {pprint.pformat(types, width=88)}\n\n'
        + f'REFERENCE = {pprint.pformat(reference, width=88)}\n'
    )
    if '--stdout' in sys.argv:
        sys.stdout.write(text)
        return 0
    path = os.path.join(ROOT, 'tests', 'temporal_binds_reference.py')
    with open(path, 'w') as f:
        f.write(text)
    # The repository's formatter has the last word on layout.
    subprocess.run(['ruff', 'format', path], check=True)
    return 0


if __name__ == '__main__':
    sys.exit(main())
